"""Tests for verify_split — the guard that a subagent's split lost no text."""

from pathlib import Path

from verify_split import verify_split

# The header betterplan-transform's splitting step writes on every section file.
# Same shape as the metadata header transform.py already writes: an HTML comment
# block terminated by a line containing only `-->`, followed by one blank line.
HEADER = "<!--\nsource: {src}\nsection: {section}\nlines: {start}-{end}\n-->\n\n"


def _write_split(section_dir: Path, src: str, sections: list[tuple[str, str]]) -> None:
    """Write an INDEX.md plus one headered section file per (filename, body)."""
    section_dir.mkdir(parents=True, exist_ok=True)
    index = ["<!-- generated by betterplan-transform — do not edit -->", f"# {src}", ""]
    line = 1
    for name, body in sections:
        end = line + body.count("\n")
        header = HEADER.format(src=src, section=name, start=line, end=end)
        (section_dir / name).write_text(header + body, encoding="utf-8")
        index.append(f"- [{name}]({name})")
        line = end + 1
    (section_dir / "INDEX.md").write_text("\n".join(index) + "\n", encoding="utf-8")


def test_exact_match_passes(tmp_path):
    original = tmp_path / "doc.md"
    original.write_text("alpha\nbeta\ngamma\n", encoding="utf-8")
    _write_split(
        tmp_path / "doc",
        "doc.pdf",
        [("01-head.md", "alpha\nbeta\n"), ("02-tail.md", "gamma\n")],
    )

    verdict = verify_split(original, tmp_path / "doc")

    assert verdict.ok
    assert verdict.section_chars == verdict.original_chars
    assert verdict.section_lines == verdict.original_lines


def test_dropped_line_fails(tmp_path):
    original = tmp_path / "doc.md"
    original.write_text("alpha\nbeta\ngamma\n", encoding="utf-8")
    _write_split(
        tmp_path / "doc",
        "doc.pdf",
        [("01-head.md", "alpha\nbeta\n"), ("02-tail.md", "")],
    )

    verdict = verify_split(original, tmp_path / "doc")

    assert not verdict.ok
    assert "line" in verdict.reason


def test_crlf_source_passes(tmp_path):
    original = tmp_path / "doc.md"
    original.write_bytes(b"alpha\r\nbeta\r\ngamma\r\n")
    _write_split(
        tmp_path / "doc",
        "doc.pdf",
        [("01-head.md", "alpha\nbeta\n"), ("02-tail.md", "gamma\n")],
    )

    assert verify_split(original, tmp_path / "doc").ok


def test_oversized_indivisible_section_passes(tmp_path):
    body = "x" * 90_000 + "\n"
    original = tmp_path / "doc.md"
    original.write_text(body, encoding="utf-8")
    _write_split(tmp_path / "doc", "doc.pdf", [("01-whole.md", body)])

    assert verify_split(original, tmp_path / "doc").ok


def test_stale_section_from_previous_run_fails(tmp_path):
    original = tmp_path / "doc.md"
    original.write_text("alpha\nbeta\ngamma\n", encoding="utf-8")
    section_dir = tmp_path / "doc"
    _write_split(
        section_dir,
        "doc.pdf",
        [("01-head.md", "alpha\nbeta\n"), ("02-tail.md", "gamma\n")],
    )
    (section_dir / "99-orphan.md").write_text(
        HEADER.format(src="doc.pdf", section="99-orphan.md", start=1, end=1) + "stale\n",
        encoding="utf-8",
    )

    verdict = verify_split(original, section_dir)

    assert not verdict.ok
    assert "99-orphan.md" in verdict.reason
